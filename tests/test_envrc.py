def venv_python(ws: Path) -> str:
    return str(ws / ".venv" / "bin" / "python")


def import_path(ws: Path, module: str) -> str | None:
    res = subprocess.run([venv_python(ws), "-c", f"import {module}; print({module}.__file__)"],
                         capture_output=True, text=True, cwd="/")
    return res.stdout.strip() if res.returncode == 0 else None


def venv_home(ws: Path) -> str:
    cfg = (ws / ".venv" / "pyvenv.cfg").read_text()
    return next(line.split("=", 1)[1].strip() for line in cfg.splitlines()
                if line.startswith("home"))


BASE_BIN = str(Path(sys.base_prefix) / "bin")


def test_venv_build_installs_and_editables(w, extra_wheel):
    w.setup(extra=f'\n[envrc.venv]\ninstall = ["{extra_wheel}"]\neditable = ["libb", "liba"]\n'
                  f'pip_args = ["--no-build-isolation"]\n')
    r = w.xwt("init")
    assert r.rc == 0, r.all
    venv = w.top / ".venv"
    pip = venv / "bin" / "pip"
    echoes = [line for line in r.out.splitlines() if line.startswith("xwt: $ ")]
    assert echoes[-4:] == [
        f"xwt: $ {BASE_BIN}/python3 -m venv --system-site-packages {venv}  (in {w.top})",
        f"xwt: $ {pip} install --ignore-installed {extra_wheel}  (in {w.top})",
        f"xwt: $ {pip} install --no-build-isolation -e .  (in {w.top / 'libb'})",
        f"xwt: $ {pip} install --no-build-isolation -e .  (in {w.top / 'liba'})",
    ]
    assert venv_home(w.top) == BASE_BIN
    assert import_path(w.top, "liba") == str(w.top / "liba" / "liba" / "__init__.py")
    assert import_path(w.top, "libb") == str(w.top / "libb" / "libb" / "__init__.py")
    assert import_path(w.top, "xwtextra").startswith(str(venv))
    # Again: the venv exists, so no creation and no `install`; the editables re-run.
    r = w.xwt("venv")
    assert r.rc == 0, r.all
    echoes = [line for line in r.out.splitlines() if line.startswith("xwt: $ ")]
    assert echoes == [
        f"xwt: $ {pip} install --no-build-isolation -e .  (in {w.top / 'libb'})",
        f"xwt: $ {pip} install --no-build-isolation -e .  (in {w.top / 'liba'})",
    ]
    assert f"xwt: using the existing {venv} (`xwt venv --recreate` rebuilds it)" in r.out


def test_new_from_a_shell_with_the_toplevels_venv_active(w, monkeypatch):
    w.setup(extra='\n[envrc.venv]\neditable = ["liba"]\npip_args = ["--no-build-isolation"]\n')
    assert w.xwt("init").rc == 0
    # Activate the toplevel's venv, as direnv would in the toplevel.
    monkeypatch.setenv("VIRTUAL_ENV", str(w.top / ".venv"))
    monkeypatch.setenv("PATH", f"{w.top / '.venv' / 'bin'}:{os.environ['PATH']}")
    r = w.xwt("new", "dev")
    assert r.rc == 0, r.all
    dev = w.group / "dev"
    assert venv_home(dev) == BASE_BIN          # seeded from the base interpreter
    assert import_path(dev, "liba") == str(dev / "liba" / "liba" / "__init__.py")
    assert import_path(w.top, "liba") == str(w.top / "liba" / "liba" / "__init__.py")
    assert w.direnv_calls() == [f"allow {w.top}", f"allow {dev}"]

    # --bare and --recreate: an empty venv.
    r = w.xwt("venv", "--recreate", "--bare", cwd=dev)
    assert r.rc == 0, r.all
    assert f"xwt: removing {dev / '.venv'}" in r.out
    assert import_path(dev, "liba") is None
    assert "pip install" not in r.out
    # Without --recreate the existing venv is kept, and the editables installed.
    r = w.xwt("venv", cwd=dev)
    assert r.rc == 0 and import_path(dev, "liba") == str(dev / "liba" / "liba" / "__init__.py")


def test_no_venv_option_and_failing_pip(w):
    w.setup(extra='\n[envrc.venv]\neditable = ["liba"]\npip_args = ["--no-such-option"]\n')
    r = w.xwt("new", "dev", "--no-venv")
    assert r.rc == 0, r.all
    dev = w.group / "dev"
    assert (dev / ".envrc").exists() and not (dev / ".venv").exists()
    r = w.xwt("new", "dev2")
    assert r.rc == 1
    dev2 = w.group / "dev2"
    assert "install --no-such-option -e .` failed (exit status 2)" in r.err
    assert (f"The worktree {dev2} is complete except for its venv; `xwt venv` in {dev2} "
            f"retries the build") in r.err
    assert w.branch(dev2 / "liba") == "dev2" and (dev2 / ".venv").exists()
    r = w.xwt("venv", cwd=dev2)
    assert r.rc == 1 and "failed (exit status 2)" in r.err


def test_failing_install_says_how_to_retry(w, tmp_path):
    w.setup(extra=f'\n[envrc.venv]\ninstall = ["{tmp_path}/missing.whl"]\n')
    r = w.xwt("init")
    assert r.rc == 1
    assert "pip install failed (exit status 1)" in r.err
    assert "`xwt venv --recreate` retries" in r.err


def test_venv_skips_a_missing_checkout(w):
    w.setup(subs=("liba",), toml=w.toml(subs=("liba",)) + '\n[envrc.venv]\neditable = ["liba"]\n')
    dev = w.add_worktree("dev", subs=())
    (dev / ".envrc").write_text(envrc_text(Project.find(w.top)))
    r = w.xwt("venv", cwd=dev)
    assert r.rc == 0, r.all
    assert (f"xwt: warning: dev has no checkout of liba (added to xwt.toml after dev was "
            f"created); run `xwt init` in {dev} to add it\n     (skipping its editable "
            f"install)") in r.err
    assert "pip install" not in r.out


def test_refused_when_envrc_is_tracked(w):
    w.setup(extra="\n[envrc.venv]\n")
    w.commit(w.top, ".envrc", "export OWN=1\n", "own .envrc")
    r = w.xwt("init")
    assert r.rc == 1
    assert (f"xwt.toml has [envrc], but .envrc is tracked in the repo ({w.top / '.envrc'}); "
            f"remove one of them") in r.err


@pytest.mark.skipif(not conda_available(), reason="needs conda and an active conda env")
def test_conda_activation(w):
    env = os.environ["CONDA_DEFAULT_ENV"]
    w.set_path(conda=True)
    w.setup(extra=f'\n[envrc]\nconda = "{env}"\n[envrc.venv]\n')
    r = w.xwt("init")
    assert r.rc == 0, r.all
    res = subprocess.run(["bash", "-c", 'cd "$1" && source ./.envrc && '
                          'echo "$CONDA_DEFAULT_ENV" && command -v python3', "x", w.top],
                         capture_output=True, text=True, check=True)
    assert res.stdout.splitlines() == [env, f"{w.top}/.venv/bin/python3"]
    # A conda env that doesn't exist stops the build.
    w.write_toml(w.toml(extra='\n[envrc]\nconda = "no-such-env-xwt"\n[envrc.venv]\n'))
    assert w.xwt("init", "--no-venv").rc == 0
    r = w.xwt("venv", "--recreate")
    assert r.rc == 1 and "can't find the base Python interpreter" in r.err
