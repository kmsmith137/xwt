HEAD = ["# Generated by xwt from [envrc] in {top}/xwt.toml.",
        "# Don't edit: change xwt.toml, then run `xwt init` here to rewrite this file."]


def text_for(tmp_path, toml):
    project = Project(tmp_path / "top", tmp_path / "top", parse(toml))
    return envrc_text(project).splitlines()


def test_envrc_conda_only(tmp_path):
    head = [h.format(top=tmp_path / "top") for h in HEAD]
    assert text_for(tmp_path, '[envrc]\nconda = "dev"\n') == head + [
        'eval "$(conda shell.bash hook)"', "conda activate dev"]
    assert text_for(tmp_path, '[envrc]\nconda = "/opt/my envs/x"\n')[-1] == \
        "conda activate '/opt/my envs/x'"


def test_envrc_venv_only(tmp_path):
    head = [h.format(top=tmp_path / "top") for h in HEAD]
    assert text_for(tmp_path, "[envrc.venv]\n") == head + [
        'export VIRTUAL_ENV="$PWD/.venv"', 'export PATH="$PWD/.venv/bin:$PATH"']


def test_envrc_both_and_exports_in_order(tmp_path):
    head = [h.format(top=tmp_path / "top") for h in HEAD]
    toml = ('[envrc]\nconda = "dev"\n[envrc.export]\nPYTHONSAFEPATH = "1"\n'
            'B = "$VIRTUAL_ENV/x"\n[envrc.venv]\n')
    assert text_for(tmp_path, toml) == head + [
        'eval "$(conda shell.bash hook)"', "conda activate dev",
        'export VIRTUAL_ENV="$PWD/.venv"', 'export PATH="$PWD/.venv/bin:$PATH"',
        'export PYTHONSAFEPATH="1"', 'export B="$VIRTUAL_ENV/x"']


def test_export_quoting_and_expansion(w):
    tricky = 'a "quoted" \\back `tick` $HOME'
    w.setup(extra=f'\n[envrc.export]\nTRICKY = {json_str(tricky)}\nVE = "$VIRTUAL_ENV/x"\n'
                  f'WS = "$PWD"\n[envrc.venv]\n')
    r = w.xwt("init", "--no-venv")
    assert r.rc == 0, r.all
    text = (w.top / ".envrc").read_text()
    assert r'export TRICKY="a \"quoted\" \\back \`tick\` $HOME"' in text
    out = subprocess.run(["bash", "-c", 'cd "$1" && source ./.envrc && '
                          'printf "%s\\n" "$TRICKY" "$VE" "$WS"', "x", w.top],
                         capture_output=True, text=True, check=True).stdout.splitlines()
    assert out == [f'a "quoted" \\back `tick` {w.home}', f"{w.top}/.venv/x", str(w.top)]


def json_str(s):
    import json
    return json.dumps(s)


