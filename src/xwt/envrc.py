"""Workspace environments (plan §6): the generated .envrc, the workspace
environment that environment steps run in, and the venv build."""

from __future__ import annotations

import os
import shlex
import shutil
import subprocess
from pathlib import Path

from . import git, ui
from .config import CONFIG_NAME
from .ui import XwtError

ENVRC = ".envrc"
VENV = ".venv"

# Sources the workspace's .envrc, then runs a command in a given directory.
# set -e while sourcing: a failing line (say, `conda activate` of an env that
# doesn't exist) must stop xwt rather than leave it in the wrong environment.
_WS_SCRIPT = 'set -e; cd "$1"; source ./.envrc; set +e; cd "$2" && shift 2 && exec "$@"'


def envrc_text(project) -> str:
    """The .envrc that xwt.toml's [envrc] produces (§6.1)."""
    ec = project.config.envrc
    lines = [
        f"# Generated by xwt from [envrc] in {project.toplevel / CONFIG_NAME}.",
        "# Don't edit: change xwt.toml, then run `xwt init` here to rewrite this file.",
    ]
    if ec.conda:
        lines.append('eval "$(conda shell.bash hook)"')
        lines.append(f"conda activate {shlex.quote(ec.conda)}")
    if ec.venv is not None:
        lines.append(f'export VIRTUAL_ENV="$PWD/{VENV}"')
        lines.append(f'export PATH="$PWD/{VENV}/bin:$PATH"')
    for name, value in ec.export.items():
        lines.append(f"export {name}={_dq(value)}")
    return "\n".join(lines) + "\n"


def _dq(value: str) -> str:
    """A double-quoted shell word: $ still expands; ", \\ and ` are escaped."""
    return '"' + "".join("\\" + c if c in '"\\`' else c for c in value) + '"'


def managed_ignores(project) -> list[str]:
    """The lines the toplevel's .gitignore needs for the paths xwt creates (§7.1)."""
    pats = [f"/{repo.key}/" for repo in project.subs]
    if project.config.envrc is not None:
        pats += ["/.envrc", "/.direnv/"]
        if project.config.envrc.venv is not None:
            pats.append("/.venv/")
    return pats


def envrc_problem(project, ws: Path) -> str | None:
    """Why xwt can't write `ws`/.envrc: the repo tracks one."""
    if git.is_tracked(ws, ENVRC):
        return (f"xwt.toml has [envrc], but .envrc is tracked in the repo ({ws / ENVRC}); "
                f"remove one of them")
    return None


def write_envrc(project, ws: Path) -> bool:
    """Write `ws`/.envrc if its content changes; True if written."""
    problem = envrc_problem(project, ws)
    if problem:
        raise XwtError(problem)
    path = Path(ws) / ENVRC
    text = envrc_text(project)
    try:
        if path.read_text() == text:
            return False
    except OSError:
        pass
    path.write_text(text)
    ui.info(f"wrote {path}")
    return True


def direnv_allow(ws: Path) -> None:
    """`direnv allow WS`, when direnv is installed: direnv blocks a changed
    .envrc until it is allowed again."""
    exe = shutil.which("direnv")
    if exe is None:
        return
    rc = git.run_echo([exe, "allow", str(ws)])
    if rc != 0:
        ui.warn(f"`direnv allow {ws}` failed (exit status {rc}); run it by hand")


# ---------------------------------------------------------------------------
# The workspace environment (§6.2)
# ---------------------------------------------------------------------------

def base_env() -> dict:
    """xwt's environment without its active venv, as direnv would leave it when
    you cd from one workspace into another."""
    env = dict(os.environ)
    venv = env.pop("VIRTUAL_ENV", None)
    if venv:
        vbin = os.path.normpath(os.path.join(venv, "bin"))
        parts = env.get("PATH", "").split(os.pathsep)
        env["PATH"] = os.pathsep.join(p for p in parts if os.path.normpath(p) != vbin)
    return env


def ws_command(ws: Path, cmd, cwd: Path | None = None) -> list[str]:
    return ["bash", "-c", _WS_SCRIPT, "xwt", str(ws), str(cwd or ws), *[str(c) for c in cmd]]


def ws_run(ws: Path, cmd, cwd: Path | None = None) -> int:
    """Echo and run `cmd` in the workspace environment, in `cwd` (default: `ws`)."""
    ui.echo(cmd, cwd or ws)
    return subprocess.run(ws_command(ws, cmd, cwd), env=base_env()).returncode


def ws_capture(ws: Path, cmd) -> subprocess.CompletedProcess:
    return subprocess.run(ws_command(ws, cmd), env=base_env(), capture_output=True, text=True)


# ---------------------------------------------------------------------------
# Building the venv (§6.3)
# ---------------------------------------------------------------------------

def build_venv(project, ws: Path, *, recreate: bool = False, bare: bool = False) -> None:
    vc = project.config.envrc.venv
    ws = Path(ws)
    venv = ws / VENV
    if recreate and os.path.lexists(venv):
        ui.info(f"removing {venv}")
        if venv.is_symlink() or not venv.is_dir():
            venv.unlink()
        else:
            shutil.rmtree(venv)

    created = False
    if not os.path.lexists(venv):
        res = ws_capture(ws, ["python3", "-c", "import sys; print(sys.base_prefix)"])
        if res.returncode != 0:
            raise XwtError(f"can't find the base Python interpreter in {ws}'s environment "
                           f"(exit status {res.returncode}):\n{res.stderr.rstrip()}")
        base = Path(res.stdout.strip().splitlines()[-1]) / "bin" / "python3"
        if not base.exists():
            raise XwtError(f"the base interpreter {base} doesn't exist")
        _step(ws, [str(base), "-m", "venv", "--system-site-packages", str(venv)])
        created = True
    else:
        ui.info(f"using the existing {venv} (`xwt venv --recreate` rebuilds it)")

    if bare:
        ui.info(f"venv ready (bare, nothing installed): {venv}")
        return

    pip = str(venv / "bin" / "pip")
    if created and vc.install:
        rc = ws_run(ws, [pip, "install", "--ignore-installed", *vc.install])
        if rc != 0:
            raise XwtError(f"pip install failed (exit status {rc}); {venv} was created "
                           f"without {', '.join(vc.install)}; `xwt venv --recreate` retries")

    for entry in vc.editable:
        if entry == ".":
            d = ws
        else:
            repo = next(r for r in project.subs if r.key == entry)
            co = next(c for c in project.checkouts(ws) if c.repo is repo)
            if not co.ok:
                ui.warn(project.reminder(co) + f"\n(skipping its editable install)")
                continue
            d = co.path
        _step(ws, [pip, "install", *vc.pip_args, "-e", "."], cwd=d)
    ui.info(f"venv ready: {venv}")


def _step(ws: Path, cmd, cwd: Path | None = None) -> None:
    rc = ws_run(ws, cmd, cwd)
    if rc != 0:
        raise XwtError(f"`{ui.cmdline(cmd)}` failed (exit status {rc})")
